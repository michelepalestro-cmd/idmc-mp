#!/usr/bin/env python3
"""build_skill_field_lessons.py - regenerate the skill's error-signature index from the KB's own lessons.

    python3 toolkit/tools/build_skill_field_lessons.py          # writes knowledge/lessons/error-index.md
    python3 toolkit/tools/build_skill_field_lessons.py --check    # exit 1 if the file is out of date

The skill's field-lessons file is the "grep this for your error string first" index. It is built ONLY from
`knowledge/lessons/lessons.jsonl` (status `current`), so it carries exactly what the KB carries: generic text, a
lesson id per row, nothing from any one deployment. Re-run it after you add lessons (the repo tests run --check).

A lesson is listed when its title or text names an error signature: an IDMC error code (APP_10519, IDS_086, TE_7002,
REPO_17315, FRS_108, V3API_..., EP_13236 ...), an HTTP 4xx/5xx status, or a quoted error message; or when its kind is
ERROR.
"""
import collections
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))  # the plugin root
SRC = os.path.join(ROOT, "knowledge", "lessons", "lessons.jsonl")
OUT = os.path.join(ROOT, "knowledge", "lessons", "error-index.md")

CODE = re.compile(r"\b(?:[A-Z][A-Za-z0-9]*_){1,3}\d{2,6}\b|\bXFER_\d{3}\b")
HTTP = re.compile(r"\b(?:HTTP |status |answers? |returns? |returned |-> ?|→ ?)([45]\d\d)\b")
QUOTED = re.compile(r"'([^']{12,90})'")
DOMAIN_TITLE = collections.OrderedDict([
    ("auth", "Access, auth & orgs"), ("agent", "Secure Agent & runtime"), ("connections", "Connections & connectors"),
    ("cdi", "Data Integration (CDI)"), ("dbmi-cdc", "Mass Ingestion & CDC"), ("cai", "Application Integration (CAI)"),
    ("dq-profiling", "Data Quality & Profiling"), ("cdgc", "Catalog & Governance (CDGC)"), ("mdm", "MDM"),
    ("claire-mcp", "CLAIRE & MCP"), ("migration", "Migration & org management"), ("org-cleanup", "Org cleanup"),
    ("ipu-licensing", "IPU, metering & licensing"), ("environment-ops", "Environment & ops"),
    ("claude-method", "Claude working methods"), ("ui-automation", "UI automation"),
])
ALIAS = {"conn": "connections", "dq": "dq-profiling", "env": "environment-ops", "mig": "migration",
         "method": "claude-method", "ui": "ui-automation"}
TEXT_MAX = 230


def signatures(x):
    blob = x["title"] + " " + x["text"]
    sig = []
    for m in CODE.findall(blob):
        if m not in sig and not m.startswith(("L_", "UTF_")):
            sig.append(m)
    for m in HTTP.findall(blob):
        if m not in sig:
            sig.append(m)
    if not sig and x.get("kind") == "ERROR":
        q = QUOTED.search(blob)
        if q:
            sig.append("'%s'" % q.group(1))
    return sig[:4]


def cell(s):
    s = " ".join(s.split()).replace("|", "\\|")
    return s if len(s) <= TEXT_MAX else s[:TEXT_MAX - 1].rstrip() + "…"


def build():
    rows = [json.loads(l) for l in open(SRC, encoding="utf-8") if l.strip()]
    cur = [x for x in rows if x.get("status") == "current"]
    by = collections.defaultdict(list)
    for x in cur:
        sig = signatures(x)
        if not sig:
            continue
        by[ALIAS.get(x["domain"], x["domain"])].append((x, sig))
    n = sum(len(v) for v in by.values())
    out = ["<!-- GENERATED by toolkit/tools/build_skill_field_lessons.py from knowledge/lessons/lessons.jsonl - do not hand-edit -->",
           "", "# Field lessons: error signatures and their causes", "",
           "%d current KB lessons that name an error code, an HTTP status or an error message, out of %d lessons." % (n, len(rows)),
           "Each row points at its lesson id in `knowledge/lessons/lessons.jsonl`, where the full text and the evidence are.",
           "", "**Grep this file for your error string first**; then open the lesson. The evidence is dated: re-probe in your",
           "own org before you rely on it, and your org's live answer wins.", ""]
    order = list(DOMAIN_TITLE) + sorted(d for d in by if d not in DOMAIN_TITLE)
    for d in order:
        if d not in by:
            continue
        out += ["## %s" % DOMAIN_TITLE.get(d, d), "", "| Signature | Lesson | What it means / the fix |", "|---|---|---|"]
        for x, sig in sorted(by[d], key=lambda t: t[0]["id"]):
            out.append("| %s | %s %s | %s |" % (cell(", ".join("`%s`" % s for s in sig)), x["id"], cell(x["title"]), cell(x["text"])))
        out.append("")
    return "\n".join(out)


def main():
    text = build()
    if "--check" in sys.argv:
        old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        print("up to date" if old == text else "OUT OF DATE: run python3 toolkit/tools/build_skill_field_lessons.py")
        return 0 if old == text else 1
    open(OUT, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote", os.path.relpath(OUT, ROOT), "(%d rows)" % (text.count("\n| ") - text.count("\n| Signature")))
    return 0


if __name__ == "__main__":
    sys.exit(main())

-- Nightly batch target in the Oracle Free PDB. The container image creates the user MBR_BATCH (APP_USER) first.
-- The CDI tasks (Copy Data template) write these tables with truncate + insert; BATCH_RUN stamps each load.
ALTER SESSION SET CONTAINER = FREEPDB1;
ALTER SESSION SET CURRENT_SCHEMA = MBR_BATCH;

CREATE TABLE MBR_ITEMS (
  ITEM VARCHAR2(40) PRIMARY KEY, ITEM_DESC VARCHAR2(250), DEPT VARCHAR2(10), CLASS VARCHAR2(10), SUBCLASS VARCHAR2(10),
  UNIT_RETAIL NUMBER(12,2), COMPARE_AT NUMBER(12,2), UPC VARCHAR2(20), SUPPLIER VARCHAR2(40), STATUS VARCHAR2(10),
  UPDATED_AT TIMESTAMP, BATCH_RUN VARCHAR2(40)
);
CREATE TABLE MBR_PO_HEADER (
  PO VARCHAR2(40) PRIMARY KEY, VERSION NUMBER(6), STATUS VARCHAR2(20), SUPPLIER VARCHAR2(40), DEPT VARCHAR2(10),
  LOCATION VARCHAR2(20), DC VARCHAR2(10), TOTAL_COST NUMBER(14,2), LINE_COUNT NUMBER(8), UPDATED_AT TIMESTAMP,
  BATCH_RUN VARCHAR2(40)
);
CREATE TABLE MBR_PO_LINE (
  PO VARCHAR2(40), LINE_NO NUMBER(8), ITEM VARCHAR2(40), LOCATION VARCHAR2(20), UNIT_COST NUMBER(12,4),
  QTY_ORDERED NUMBER(12,2), BATCH_RUN VARCHAR2(40), CONSTRAINT MBR_PO_LINE_PK PRIMARY KEY (PO, LINE_NO)
);

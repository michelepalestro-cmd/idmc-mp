-- Bid Desk 02: Bronze = what IDMC read, appended per run. Idempotent. Schema ${snowflake.database}.${snowflake.schema}.
USE SCHEMA ${snowflake.database}.${snowflake.schema};

-- mapping 1, flow A: the agencies (Salesforce Account)
CREATE TABLE IF NOT EXISTS BID_BRZ_SF_AGENCY (
  ID VARCHAR(18), NAME VARCHAR(255), ACCOUNT_TYPE VARCHAR(40), SF_SOURCE VARCHAR(40), IDMC_RUN_ID VARCHAR(20), LOADED_AT TIMESTAMP_NTZ)
  COMMENT = 'Bid Desk Bronze: the agencies as IDMC read them from the CRM (Account)';

-- mapping 1, flow B: every version of every bid document attached to an agency (Salesforce Files = ContentVersion),
-- the PDF bytes as base64 TEXT (a BINARY column cannot feed a CDI source: 'Unknown native type', KB L-CONN-113)
CREATE TABLE IF NOT EXISTS BID_BRZ_SF_DOCUMENT (
  CONTENT_VERSION_ID VARCHAR(18), CONTENT_DOCUMENT_ID VARCHAR(18), AGENCY_ID VARCHAR(18), AGENCY VARCHAR(255),
  TITLE VARCHAR(255), FILE_NAME VARCHAR(500), FILE_EXTENSION VARCHAR(40), VERSION_NUMBER VARCHAR(20), CONTENT_SIZE NUMBER(12, 0),
  CHECKSUM VARCHAR(50), SF_CREATED_AT TIMESTAMP_NTZ, REASON_FOR_CHANGE VARCHAR(1000), DOC_TYPE VARCHAR(40), SOLICITATION_NO VARCHAR(40),
  CONTENT_B64 VARCHAR(16777216), SF_SOURCE VARCHAR(40), IDMC_RUN_ID VARCHAR(20), LOADED_AT TIMESTAMP_NTZ)
  COMMENT = 'Bid Desk Bronze: the bid documents attached to the agencies in the CRM (one row per file version, bytes as base64)';

-- the documents in play: the newest version of each document. Salesforce sets FirstPublishLocationId on version 1 only
-- (KB L-CONN-114), so a later version takes its document's agency from version 1.
CREATE OR REPLACE VIEW BID_V_DOCUMENTS AS
SELECT D.CONTENT_VERSION_ID, D.CONTENT_DOCUMENT_ID,
       COALESCE(D.AGENCY_ID, MAX(D.AGENCY_ID) OVER (PARTITION BY D.CONTENT_DOCUMENT_ID)) AS AGENCY_ID,
       COALESCE(D.AGENCY, MAX(D.AGENCY) OVER (PARTITION BY D.CONTENT_DOCUMENT_ID)) AS AGENCY,
       D.TITLE, D.FILE_NAME, D.VERSION_NUMBER, D.CONTENT_SIZE, D.CHECKSUM, D.SF_CREATED_AT, D.REASON_FOR_CHANGE, D.DOC_TYPE,
       D.SOLICITATION_NO, D.CONTENT_B64, D.IDMC_RUN_ID, D.LOADED_AT,
       COALESCE(D.AGENCY, MAX(D.AGENCY) OVER (PARTITION BY D.CONTENT_DOCUMENT_ID)) || ' - ' || D.SOLICITATION_NO AS SP_FOLDER,
       D.TITLE || IFF(D.VERSION_NUMBER = '1', '', ' (v' || D.VERSION_NUMBER || ')') || '.' || LOWER(COALESCE(D.FILE_EXTENSION, 'pdf')) AS SP_FILE_NAME
FROM BID_BRZ_SF_DOCUMENT D
QUALIFY ROW_NUMBER() OVER (PARTITION BY D.CONTENT_DOCUMENT_ID ORDER BY TRY_TO_NUMBER(D.VERSION_NUMBER) DESC, D.LOADED_AT DESC) = 1;

-- mappings 2a / 2b: what CLAIRE read. The named columns are the canonical fields the Silver views use; map the model's
-- output fields onto them (bid_claire_models.py fields <key> proposes the map). TEXT_nn = every free-text block the model
-- exports (the tuned model exports them all, so no line of the document is lost).
CREATE TABLE IF NOT EXISTS BID_BRZ_BID_PACKET (
  CONTENT_VERSION_ID VARCHAR(18), AGENCY VARCHAR(255), TITLE VARCHAR(255), SOLICITATION_NO VARCHAR(40), VERSION_NUMBER VARCHAR(20),
  FILE_NAME VARCHAR(500),
  COMPANY_BIDDER VARCHAR(2000), BID_CONTACT VARCHAR(2000), BID_CONTACT_EMAIL VARCHAR(2000), BID_CONTACT_PHONE VARCHAR(2000),
  SALES_CONTACT VARCHAR(2000), SERVICE_CONTACT VARCHAR(2000), TIME_TO_DELIVER VARCHAR(2000), SIGNATURE VARCHAR(2000),
  PAYMENT_TERMS VARCHAR(2000), BIDDER VARCHAR(2000),
  ITEM_NO VARCHAR(2000), ITEM_DESCRIPTION VARCHAR(2000), UNIT VARCHAR(2000), QTY_NEEDED VARCHAR(2000), UNIT_PRICE VARCHAR(2000),
  BRAND_BID VARCHAR(2000), CURRENT_PRODUCT VARCHAR(2000), BID_NOTES VARCHAR(2000),
  TEXT_01 VARCHAR(16000), TEXT_02 VARCHAR(16000), TEXT_03 VARCHAR(16000), TEXT_04 VARCHAR(16000), TEXT_05 VARCHAR(16000),
  TEXT_06 VARCHAR(16000), TEXT_07 VARCHAR(16000), TEXT_08 VARCHAR(16000), TEXT_09 VARCHAR(16000), TEXT_10 VARCHAR(16000),
  TEXT_11 VARCHAR(16000), TEXT_12 VARCHAR(16000), TEXT_13 VARCHAR(16000), TEXT_14 VARCHAR(16000), TEXT_15 VARCHAR(16000),
  TEXT_16 VARCHAR(16000), TEXT_17 VARCHAR(16000), TEXT_18 VARCHAR(16000), TEXT_19 VARCHAR(16000), TEXT_20 VARCHAR(16000),
  ISM_NAME VARCHAR(100), IDMC_RUN_ID VARCHAR(20), LOADED_AT TIMESTAMP_NTZ)
  COMMENT = 'Bid Desk Bronze: what CLAIRE read from the bid packet (one row per bid-form line, the packet fields on each)';

CREATE TABLE IF NOT EXISTS BID_BRZ_SIGNATURE_PAGE (

-- mapping 1b: the transfer log (one row per file version IDMC uploaded to SharePoint)
CREATE TABLE IF NOT EXISTS BID_BRZ_SP_TRANSFER (
  CONTENT_VERSION_ID VARCHAR(18), CONTENT_DOCUMENT_ID VARCHAR(18), AGENCY VARCHAR(255), SOLICITATION_NO VARCHAR(40), TITLE VARCHAR(255),
  VERSION_NUMBER VARCHAR(20), SP_FOLDER VARCHAR(1000), SP_PATH VARCHAR(1000), IDMC_RUN_ID VARCHAR(20), TRANSFERRED_AT TIMESTAMP_NTZ)
  COMMENT = 'Bid Desk transfer log: the CRM bid documents IDMC transferred to SharePoint';

-- mapping 5: the reset log (one row per document set back to the agency original)
CREATE TABLE IF NOT EXISTS BID_RESET_LOG (RESET_AT TIMESTAMP_NTZ, RUN_ID VARCHAR(20), CONTENT_DOCUMENT_ID VARCHAR(18), TITLE VARCHAR(255),
  REPLACED_VERSION VARCHAR(20)) COMMENT = 'Bid Desk: each reset of a bid document to the agency original (a new CRM file version)';
